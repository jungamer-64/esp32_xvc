fn core1_main() -> ! {
    println!("[Core1] Ready");

    loop {
        let mut spins = 0u32;
        while MBOX.cmd.load(Ordering::Relaxed) == CMD_NONE {
            if spins < 200 {
                rtos_yield();
                spins += 1;
            } else {
                rtos_delay_ms(1);
            }
        }

        let cmd = MBOX.cmd.swap(CMD_NONE, Ordering::AcqRel);
        if cmd == CMD_NONE {
            continue;
        }

        let seq = MBOX.active_seq.load(Ordering::Acquire);
        if seq == 0 {
            println!("Core1: FATAL active_seq=0, logic error");
            MBOX.state.store(ST_ERR, Ordering::Relaxed);
            MBOX.done_seq.store(u32::MAX, Ordering::Release);
            continue;
        }

        MBOX.state.store(ST_BUSY, Ordering::Relaxed);

        match cmd {
            CMD_RESET => {
                let tck_us = MBOX.tck_period_us.load(Ordering::Acquire);
                let ok = tap_reset_fast(tck_us);
                MBOX.state
                    .store(if ok { ST_DONE } else { ST_ERR }, Ordering::Relaxed);
            }
            CMD_SHIFT => {
                let tck_us = MBOX.tck_period_us.load(Ordering::Acquire);
                let num_bits = MBOX.num_bits.load(Ordering::Acquire) as usize;
                let num_bytes = bits_to_bytes(num_bits);

                let tms_ptr = MBOX.tms_ptr.load(Ordering::Acquire) as *const u8;
                let tdi_ptr = MBOX.tdi_ptr.load(Ordering::Acquire) as *const u8;
                let tdo_ptr = MBOX.tdo_ptr.load(Ordering::Acquire) as *mut u8;

                let ok = unsafe {
                    let tms = core::slice::from_raw_parts(tms_ptr, num_bytes);
                    let tdi = core::slice::from_raw_parts(tdi_ptr, num_bytes);
                    let tdo = core::slice::from_raw_parts_mut(tdo_ptr, num_bytes);
                    shift_bits_fast(tck_us, tms, tdi, tdo, num_bits)
                };

                MBOX.state
                    .store(if ok { ST_DONE } else { ST_ERR }, Ordering::Relaxed);
            }
            _ => {
                MBOX.state.store(ST_ERR, Ordering::Relaxed);
            }
        }

        MBOX.done_seq.store(seq, Ordering::Release);
    }
}

struct PendingRef {
    ptr: *const u8,
    len: usize,
    sent: usize,
}

impl PendingRef {
    const fn new() -> Self {
        Self {
            ptr: core::ptr::null(),
            len: 0,
            sent: 0,
        }
    }

    fn set_ref(&mut self, data: &[u8]) {
        self.ptr = data.as_ptr();
        self.len = data.len();
        self.sent = 0;
    }

    fn pending(&self) -> &[u8] {
        if self.ptr.is_null() {
            &[]
        } else {
            unsafe { core::slice::from_raw_parts(self.ptr.add(self.sent), self.len - self.sent) }
        }
    }

    fn advance(&mut self, n: usize) {
        self.sent = self.sent.saturating_add(n).min(self.len);
    }

    fn is_complete(&self) -> bool {
        self.sent >= self.len
    }

    fn clear(&mut self) {
        self.ptr = core::ptr::null();
        self.len = 0;
        self.sent = 0;
    }
}

struct XvcResult {
    consumed: usize,
    response_len: usize,
    close_connection: bool,
    streaming_shift_bits: usize,
}

fn try_process_one_command<F>(
    data: &[u8],
    out_ptr: *mut u8,
    out_cap: usize,
    jtag: &mut JtagController,
    mut poll_fn: F,
) -> Option<XvcResult>
where
    F: FnMut() -> bool,
{
    if data.len() >= 6 && data.starts_with(b"shift:") {
        if data.len() < 10 {
            return None;
        }

        let num_bits = u32::from_le_bytes([data[6], data[7], data[8], data[9]]) as usize;

        if num_bits > MAX_SHIFT_BITS {
            return Some(XvcResult {
                consumed: 10,
                response_len: 0,
                close_connection: false,
                streaming_shift_bits: num_bits,
            });
        }

        let num_bytes = bits_to_bytes(num_bits);
        let payload_len = num_bytes.checked_mul(2)?;
        let total_len = 10usize.checked_add(payload_len)?;

        if data.len() < total_len {
            return None;
        }

        if num_bytes > out_cap {
            println!("Error: Response buffer overflow");
            return Some(XvcResult {
                consumed: 0,
                response_len: 0,
                close_connection: true,
                streaming_shift_bits: 0,
            });
        }

        let seq = next_seq();
        let _token = match TokenGuard::acquire(seq) {
            Some(guard) => guard,
            None => {
                println!("Error: JTAG busy re-entry");
                return Some(XvcResult {
                    consumed: 0,
                    response_len: 0,
                    close_connection: true,
                    streaming_shift_bits: 0,
                });
            }
        };

        let tms_ptr = data.as_ptr().wrapping_add(10) as usize;
        let tdi_ptr = data.as_ptr().wrapping_add(10 + num_bytes) as usize;

        MBOX.state.store(ST_IDLE, Ordering::Relaxed);
        MBOX.abort.store(false, Ordering::Relaxed);
        MBOX.tck_period_us
            .store(jtag.tck_period_us, Ordering::Relaxed);
        MBOX.num_bits.store(num_bits as u32, Ordering::Relaxed);
        MBOX.tms_ptr.store(tms_ptr, Ordering::Relaxed);
        MBOX.tdi_ptr.store(tdi_ptr, Ordering::Relaxed);
        MBOX.tdo_ptr.store(out_ptr as usize, Ordering::Relaxed);
        MBOX.active_seq.store(seq, Ordering::Relaxed);

        if MBOX
            .cmd
            .compare_exchange(CMD_NONE, CMD_SHIFT, Ordering::Release, Ordering::Relaxed)
            .is_err()
        {
            println!("FATAL: cmd not consumed (SHIFT)");
            unsafe { software_reset() };
        }

        let tck_us = jtag.tck_period_us as i64;
        let expected_ms = (num_bits as i64).saturating_mul(tck_us).saturating_add(999) / 1000;
        let deadline = get_time_ms()
            .saturating_add(expected_ms.saturating_mul(2))
            .saturating_add(200);
        let hard_deadline = deadline.saturating_add(2000);

        let mut timed_out = false;
        loop {
            if !poll_fn() {
                MBOX.abort.store(true, Ordering::Release);
            }

            if MBOX.done_seq.load(Ordering::Acquire) == seq {
                break;
            }

            let now = get_time_ms();
            if now > deadline && !timed_out {
                xvc_log!("Core1 timeout ({}bits)", num_bits);
                MBOX.abort.store(true, Ordering::Release);
                timed_out = true;
            }

            if now > hard_deadline {
                println!("CRITICAL: Core1 stuck (SHIFT)");
                unsafe { software_reset() };
            }

            rtos_yield();
        }

        let state = MBOX.state.load(Ordering::Acquire);
        if state != ST_DONE {
            println!("Shift failed (state={})", state);
            return Some(XvcResult {
                consumed: 0,
                response_len: 0,
                close_connection: true,
                streaming_shift_bits: 0,
            });
        }

        if num_bits % 8 != 0 {
            let mask = (1u8 << (num_bits % 8)) - 1;
            unsafe {
                let out = core::slice::from_raw_parts_mut(out_ptr, num_bytes);
                out[num_bytes - 1] &= mask;
            }
        }

        #[cfg(feature = "xvc-log")]
        {
            let tdo_slice = unsafe { core::slice::from_raw_parts(out_ptr, num_bytes.min(8)) };
            let tms_slice =
                unsafe { core::slice::from_raw_parts(tms_ptr as *const u8, num_bytes.min(4)) };
            let tdi_slice =
                unsafe { core::slice::from_raw_parts(tdi_ptr as *const u8, num_bytes.min(4)) };
            xvc_log!(
                "shift: {}bits TMS={:02x?} TDI={:02x?} -> TDO={:02x?}",
                num_bits,
                tms_slice,
                tdi_slice,
                tdo_slice
            );
        }

        return Some(XvcResult {
            consumed: total_len,
            response_len: num_bytes,
            close_connection: false,
            streaming_shift_bits: 0,
        });
    }

    if data.len() < 8 {
        return None;
    }

    if data.starts_with(b"getinfo:") {
        let len = GETINFO_RESPONSE.len().min(out_cap);
        unsafe {
            core::ptr::copy_nonoverlapping(GETINFO_RESPONSE.as_ptr(), out_ptr, len);
        }
        return Some(XvcResult {
            consumed: 8,
            response_len: len,
            close_connection: false,
            streaming_shift_bits: 0,
        });
    }

    if data.starts_with(b"settck:") {
        if data.len() < 11 {
            return None;
        }
        if out_cap < 4 {
            return Some(XvcResult {
                consumed: 0,
                response_len: 0,
                close_connection: true,
                streaming_shift_bits: 0,
            });
        }

        let req_period_ns = u32::from_le_bytes([data[7], data[8], data[9], data[10]]);
        jtag.set_tck_period(req_period_ns);

        let applied_ns = jtag.get_tck_period_ns().to_le_bytes();
        unsafe {
            core::ptr::copy_nonoverlapping(applied_ns.as_ptr(), out_ptr, 4);
        }

        return Some(XvcResult {
            consumed: 11,
            response_len: 4,
            close_connection: false,
            streaming_shift_bits: 0,
        });
    }

    let log_len = data.len().min(16);
    println!(
        "Protocol Error: Unknown command. First {} bytes: {:02x?} ({:?})",
        log_len,
        &data[..log_len],
        core::str::from_utf8(&data[..log_len]).unwrap_or(".")
    );

    Some(XvcResult {
        consumed: 0,
        response_len: 0,
        close_connection: true,
        streaming_shift_bits: 0,
    })
}

// Timer for smoltcp. Only Core0 accesses START_TIME after initialization.
static mut START_TIME: Option<Instant> = None;

fn get_time_ms() -> i64 {
    unsafe {
        match START_TIME {
            Some(start) => start.elapsed().as_millis() as i64,
            None => 0,
        }
    }
}

fn init_time() {
    unsafe {
        START_TIME = Some(Instant::now());
    }
}

#[panic_handler]
fn panic(info: &core::panic::PanicInfo) -> ! {
    println!("Panic: {:?}", info);
    unsafe { software_reset() };
    loop {}
}

/// Abort an active JTAG command and wait until Core1 stops touching shared buffers.
fn abort_jtag_and_wait_done() {
    let seq = JTAG_TOKEN.load(Ordering::Acquire);
    if seq == 0 {
        return;
    }

    xvc_log!("Waiting for Core1 (seq={})...", seq);
    MBOX.abort.store(true, Ordering::Release);

    let deadline = get_time_ms().saturating_add(2000);

    while MBOX.done_seq.load(Ordering::Acquire) != seq {
        if JTAG_TOKEN.load(Ordering::Relaxed) == 0 {
            xvc_log!("abort: token dropped while waiting, exiting");
            break;
        }

        if get_time_ms() > deadline {
            println!("CRITICAL: Core1 stuck, resetting");
            unsafe { software_reset() };
        }
        rtos_yield();
    }
}

fn reset_connection(
    sockets: &mut SocketSet,
    tcp_handle: SocketHandle,
    rx_head: &mut usize,
    rx_len: &mut usize,
    pending: &mut PendingRef,
    pending_start_ms: &mut Option<i64>,
) {
    abort_jtag_and_wait_done();

    {
        let socket = sockets.get_mut::<TcpSocket>(tcp_handle);
        socket.abort();
    }

    *rx_head = 0;
    *rx_len = 0;
    pending.clear();
    *pending_start_ms = None;
    MBOX.abort.store(false, Ordering::Release);
}

#[esp_hal::main]
