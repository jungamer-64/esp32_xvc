use core::cell::UnsafeCell;

/// Buffers shared between Core0 and Core1 during JTAG operations.
struct JtagBuffers {
    tms_buf: UnsafeCell<[u8; CHUNK_BYTES]>,
    tdi_buf: UnsafeCell<[u8; CHUNK_BYTES]>,
    tdo_bufs: [UnsafeCell<[u8; CHUNK_BYTES]>; 2],

    /// Deterministic storage for all TMS bytes up to GETINFO_MAX_BITS.
    raw_tms_buf: UnsafeCell<[u8; RAW_FALLBACK_MAX_BYTES]>,
}

// SAFETY: Access is synchronized by JTAG_TOKEN and MBOX.done_seq.
unsafe impl Sync for JtagBuffers {}

impl JtagBuffers {
    const fn new() -> Self {
        Self {
            tms_buf: UnsafeCell::new([0u8; CHUNK_BYTES]),
            tdi_buf: UnsafeCell::new([0u8; CHUNK_BYTES]),
            tdo_bufs: [
                UnsafeCell::new([0u8; CHUNK_BYTES]),
                UnsafeCell::new([0u8; CHUNK_BYTES]),
            ],
            raw_tms_buf: UnsafeCell::new([0u8; RAW_FALLBACK_MAX_BYTES]),
        }
    }

    fn tms_ptr(&self) -> *mut u8 {
        self.tms_buf.get() as *mut u8
    }

    fn tdi_ptr(&self) -> *mut u8 {
        self.tdi_buf.get() as *mut u8
    }

    fn tdo_ptr(&self, slot: usize) -> *mut u8 {
        self.tdo_bufs[slot].get() as *mut u8
    }

    unsafe fn tms_slice_mut(&self) -> &mut [u8; CHUNK_BYTES] {
        unsafe { &mut *self.tms_buf.get() }
    }

    unsafe fn tdi_slice_mut(&self) -> &mut [u8; CHUNK_BYTES] {
        unsafe { &mut *self.tdi_buf.get() }
    }

    unsafe fn tdo_slice(&self, slot: usize) -> &[u8; CHUNK_BYTES] {
        unsafe { &*self.tdo_bufs[slot].get() }
    }

    unsafe fn raw_tms_slice_mut(&self) -> &mut [u8; RAW_FALLBACK_MAX_BYTES] {
        unsafe { &mut *self.raw_tms_buf.get() }
    }

    unsafe fn raw_tms_slice(&self) -> &[u8; RAW_FALLBACK_MAX_BYTES] {
        unsafe { &*self.raw_tms_buf.get() }
    }

    unsafe fn mask_tdo_last_byte(&self, slot: usize, chunk_bytes: usize, chunk_bits: usize) {
        unsafe {
            if chunk_bits % 8 != 0 {
                let mask = (1u8 << (chunk_bits % 8)) - 1;
                (*self.tdo_bufs[slot].get())[chunk_bytes - 1] &= mask;
            }
        }
    }
}

static JTAG_BUFS: JtagBuffers = JtagBuffers::new();

/// Reusable metadata for streaming shifts.
///
/// - Shifts up to GETINFO_MAX_BITS use static RAW TMS storage.
/// - Larger shifts use bounded RLE storage and fail safely if TMS is too complex.
/// - TDO uses two ping-pong buffers.
struct StreamContext {
    tms_rle: TmsRle,
    use_raw: bool,
    raw_len: usize,
    raw_pos: usize,

    tdo_lens: [usize; 2],
    tdo_sent: [usize; 2],
    tdo_fill_slot: usize,
    tdo_pending: usize,
}

impl StreamContext {
    fn new() -> Self {
        let mut ctx = Self {
            tms_rle: TmsRle::new(),
            use_raw: false,
            raw_len: 0,
            raw_pos: 0,
            tdo_lens: [0; 2],
            tdo_sent: [0; 2],
            tdo_fill_slot: 0,
            tdo_pending: 0,
        };

        let _ = ctx.tms_rle.runs.try_reserve(64);
        ctx
    }

    fn reset(&mut self) {
        self.tms_rle.clear();
        self.use_raw = false;
        self.raw_len = 0;
        self.raw_pos = 0;
        self.tdo_lens = [0; 2];
        self.tdo_sent = [0; 2];
        self.tdo_fill_slot = 0;
        self.tdo_pending = 0;
    }

    fn current_tdo_slot(&self) -> usize {
        self.tdo_fill_slot
    }

    fn enqueue_tdo(&mut self, len: usize) {
        self.tdo_lens[self.tdo_fill_slot] = len;
        self.tdo_sent[self.tdo_fill_slot] = 0;
        self.tdo_pending += 1;
        self.tdo_fill_slot = 1 - self.tdo_fill_slot;
    }

    fn oldest_pending_slot(&self) -> Option<usize> {
        if self.tdo_pending == 0 {
            None
        } else if self.tdo_pending == 1 {
            Some(1 - self.tdo_fill_slot)
        } else {
            Some(self.tdo_fill_slot)
        }
    }

    fn prepare_for_read(&mut self) {
        if self.use_raw {
            self.raw_pos = 0;
        } else {
            self.tms_rle.reset_cursor();
        }
    }

    fn fill_tms_into_buf(&mut self, len: usize) -> Result<(), StreamError> {
        debug_assert!(len <= CHUNK_BYTES);

        if self.use_raw {
            let end = self
                .raw_pos
                .checked_add(len)
                .ok_or(StreamError::TmsUnderflow)?;
            if end > self.raw_len {
                return Err(StreamError::TmsUnderflow);
            }

            unsafe {
                let src = &JTAG_BUFS.raw_tms_slice()[self.raw_pos..end];
                JTAG_BUFS.tms_slice_mut()[..len].copy_from_slice(src);
            }
            self.raw_pos = end;
            Ok(())
        } else {
            let buf_slice = unsafe { &mut JTAG_BUFS.tms_slice_mut()[..len] };
            self.tms_rle.fill(buf_slice)
        }
    }
}

use smoltcp::phy::Device;

/// Receive exactly `buf.len()` bytes while polling the network.
fn recv_exact<D: Device>(
    tcp_handle: SocketHandle,
    buf: &mut [u8],
    iface: &mut Interface,
    device: &mut D,
    sockets: &mut SocketSet,
) -> Result<(), StreamError> {
    let mut received = 0usize;
    let mut last_progress_ms = get_time_ms();

    while received < buf.len() {
        let ts = SmolInstant::from_millis(get_time_ms());
        iface.poll(ts, device, sockets);

        let socket = sockets.get_mut::<TcpSocket>(tcp_handle);

        if !socket.may_recv() {
            return Err(StreamError::Disconnected);
        }

        if !socket.can_recv() {
            if get_time_ms().saturating_sub(last_progress_ms) > STREAM_RECV_TIMEOUT_MS {
                return Err(StreamError::Timeout);
            }
            rtos_yield();
            continue;
        }

        match socket.recv_slice(&mut buf[received..]) {
            Ok(0) => {
                if !socket.may_recv() {
                    return Err(StreamError::Disconnected);
                }
                if get_time_ms().saturating_sub(last_progress_ms) > STREAM_RECV_TIMEOUT_MS {
                    return Err(StreamError::Timeout);
                }
                rtos_yield();
            }
            Ok(n) => {
                received += n;
                last_progress_ms = get_time_ms();
            }
            Err(smoltcp::socket::tcp::RecvError::InvalidState) => {
                return Err(StreamError::Disconnected);
            }
            Err(smoltcp::socket::tcp::RecvError::Finished) => {
                return Err(StreamError::Disconnected);
            }
            #[allow(unreachable_patterns)]
            Err(_) => {
                rtos_yield();
            }
        }
    }

    Ok(())
}

/// Read exact bytes, first consuming buffered XVC bytes and then the socket.
fn read_exact_mix<D: Device>(
    tcp_handle: SocketHandle,
    dst: &mut [u8],
    xvc_rx: &mut [u8],
    rx_head: &mut usize,
    rx_len: &mut usize,
    iface: &mut Interface,
    device: &mut D,
    sockets: &mut SocketSet,
) -> Result<(), StreamError> {
    let mut off = 0usize;

    while off < dst.len() && *rx_len > 0 {
        let take = core::cmp::min(dst.len() - off, *rx_len);
        dst[off..off + take].copy_from_slice(&xvc_rx[*rx_head..*rx_head + take]);
        *rx_head += take;
        *rx_len -= take;
        off += take;

        if *rx_len == 0 {
            *rx_head = 0;
        }
    }

    if off < dst.len() {
        recv_exact(tcp_handle, &mut dst[off..], iface, device, sockets)?;
    }

    Ok(())
}

/// Send all bytes while polling the network.
#[allow(dead_code)]
fn send_all<D: Device>(
    tcp_handle: SocketHandle,
    buf: &[u8],
    iface: &mut Interface,
    device: &mut D,
    sockets: &mut SocketSet,
) -> Result<(), StreamError> {
    let mut sent = 0usize;
    let mut last_progress_ms = get_time_ms();

    while sent < buf.len() {
        let ts = SmolInstant::from_millis(get_time_ms());
        iface.poll(ts, device, sockets);

        let socket = sockets.get_mut::<TcpSocket>(tcp_handle);

        if !socket.may_send() {
            return Err(StreamError::Disconnected);
        }

        if !socket.can_send() {
            if get_time_ms().saturating_sub(last_progress_ms) > STREAM_SEND_TIMEOUT_MS {
                return Err(StreamError::Timeout);
            }
            rtos_yield();
            continue;
        }

        match socket.send_slice(&buf[sent..]) {
            Ok(0) => {
                if !socket.may_send() {
                    return Err(StreamError::Disconnected);
                }
                if get_time_ms().saturating_sub(last_progress_ms) > STREAM_SEND_TIMEOUT_MS {
                    return Err(StreamError::Timeout);
                }
                rtos_yield();
            }
            Ok(n) => {
                sent += n;
                last_progress_ms = get_time_ms();
            }
            Err(smoltcp::socket::tcp::SendError::InvalidState) => {
                return Err(StreamError::Disconnected);
            }
            #[allow(unreachable_patterns)]
            Err(_) => {
                rtos_yield();
            }
        }
    }

    Ok(())
}

enum DrainResult {
    ProgressMade,
    NoProgress,
    Disconnected,
}

fn try_drain_tdo<D: Device>(
    tcp_handle: SocketHandle,
    ctx: &mut StreamContext,
    iface: &mut Interface,
    device: &mut D,
    sockets: &mut SocketSet,
) -> DrainResult {
    let mut made_progress = false;

    while ctx.tdo_pending > 0 {
        let slot = match ctx.oldest_pending_slot() {
            Some(slot) => slot,
            None => break,
        };

        if ctx.tdo_sent[slot] >= ctx.tdo_lens[slot] {
            ctx.tdo_lens[slot] = 0;
            ctx.tdo_sent[slot] = 0;
            ctx.tdo_pending = ctx.tdo_pending.saturating_sub(1);
            continue;
        }

        let socket = sockets.get_mut::<TcpSocket>(tcp_handle);

        if !socket.may_send() {
            return DrainResult::Disconnected;
        }

        if !socket.can_send() {
            break;
        }

        let start = ctx.tdo_sent[slot];
        let end = ctx.tdo_lens[slot];
        debug_assert!(
            start <= end,
            "TDO sent > len: slot={} sent={} len={}",
            slot,
            start,
            end
        );

        let buf = unsafe { JTAG_BUFS.tdo_slice(slot) };
        match socket.send_slice(&buf[start..end]) {
            Ok(n) if n > 0 => {
                made_progress = true;
                ctx.tdo_sent[slot] += n;

                if ctx.tdo_sent[slot] >= ctx.tdo_lens[slot] {
                    ctx.tdo_pending -= 1;
                }
            }
            Ok(_) => break,
            Err(smoltcp::socket::tcp::SendError::InvalidState) => {
                return DrainResult::Disconnected;
            }
            #[allow(unreachable_patterns)]
            Err(_) => break,
        }

        let ts = SmolInstant::from_millis(get_time_ms());
        iface.poll(ts, device, sockets);
    }

    if made_progress {
        DrainResult::ProgressMade
    } else {
        DrainResult::NoProgress
    }
}

fn flush_tdo<D: Device>(
    tcp_handle: SocketHandle,
    ctx: &mut StreamContext,
    iface: &mut Interface,
    device: &mut D,
    sockets: &mut SocketSet,
) -> Result<(), StreamError> {
    let mut last_progress_ms = get_time_ms();

    while ctx.tdo_pending > 0 {
        let ts = SmolInstant::from_millis(get_time_ms());
        iface.poll(ts, device, sockets);

        match try_drain_tdo(tcp_handle, ctx, iface, device, sockets) {
            DrainResult::Disconnected => return Err(StreamError::Disconnected),
            DrainResult::ProgressMade => last_progress_ms = get_time_ms(),
            DrainResult::NoProgress => {}
        }

        if ctx.tdo_pending > 0 {
            if get_time_ms().saturating_sub(last_progress_ms) > STREAM_SEND_TIMEOUT_MS {
                println!(
                    "Stream: TDO flush timeout (pending={}, fill_slot={})",
                    ctx.tdo_pending, ctx.tdo_fill_slot
                );
                return Err(StreamError::Timeout);
            }
            rtos_yield();
        }
    }

    Ok(())
}

/// CRITICAL: MANDATORY VIVADO COMPATIBILITY PATH — DO NOT REMOVE.
///
/// Vivado may ignore the shift-size value advertised by `getinfo:` and send a
/// shift that cannot fit in the normal fixed-size receive buffer.
///
/// This function is not an optional optimization. Do not remove it, disable it,
/// or replace it with fixed-size-only shift handling unless an equivalent
/// bounded-memory large-shift implementation is provided.
///
/// Any replacement must preserve large-shift support, TMS retention or
/// reconstruction until TDI arrives, incremental JTAG execution, TDO delivery,
/// timeout handling, disconnect aborts, and Core0/Core1 synchronization.
///
/// Process a large shift command via two-pass streaming.
///
/// XVC sends all TMS bytes before all TDI bytes, so Phase A stores/compresses TMS
/// and Phase B receives TDI chunks, performs JTAG, and streams TDO back.
fn stream_shift_command<D: Device>(
    num_bits: usize,
    jtag: &mut JtagController,
    sockets: &mut SocketSet,
    tcp_handle: SocketHandle,
    iface: &mut Interface,
    device: &mut D,
    xvc_rx: &mut [u8],
    rx_head: &mut usize,
    rx_len: &mut usize,
    ctx: &mut StreamContext,
) -> Result<(), StreamError> {
    // Validate before any rounding arithmetic. num_bits originates from the network.
    if num_bits > STREAM_ABS_MAX_BITS {
        println!(
            "Shift too large: {} bits (max {})",
            num_bits, STREAM_ABS_MAX_BITS
        );
        return Err(StreamError::ShiftTooLarge);
    }

    let num_bytes = bits_to_bytes(num_bits);

    xvc_log!("Stream start: {} bits ({} bytes)", num_bits, num_bytes);
    let stream_start_ms = get_time_ms();

    ctx.reset();

    // Requests up to the advertised GETINFO size use deterministic static RAW storage.
    // Larger requests must be RLE-friendly and are bounded to 1024 runs.
    ctx.use_raw = num_bytes <= RAW_FALLBACK_MAX_BYTES;
    let max_runs = 1024usize;

    let mut tmp = [0u8; CHUNK_BYTES];
    let mut tms_tail = [0u8; 4];
    let mut tms_seen = 0usize;
    let mut tms_remain = num_bytes;

    while tms_remain > 0 {
        let n = tms_remain.min(tmp.len());
        read_exact_mix(
            tcp_handle,
            &mut tmp[..n],
            xvc_rx,
            rx_head,
            rx_len,
            iface,
            device,
            sockets,
        )?;

        // Keep the real final four bytes regardless of chunk boundaries.
        for &b in &tmp[..n] {
            if tms_seen < tms_tail.len() {
                tms_tail[tms_seen] = b;
            } else {
                tms_tail.rotate_left(1);
                tms_tail[3] = b;
            }
            tms_seen += 1;
        }

        if ctx.use_raw {
            let end = ctx
                .raw_len
                .checked_add(n)
                .ok_or(StreamError::ShiftTooLarge)?;
            if end > RAW_FALLBACK_MAX_BYTES {
                return Err(StreamError::ShiftTooLarge);
            }

            unsafe {
                JTAG_BUFS.raw_tms_slice_mut()[ctx.raw_len..end].copy_from_slice(&tmp[..n]);
            }
            ctx.raw_len = end;
        } else {
            for &b in &tmp[..n] {
                ctx.tms_rle.push_byte(b, max_runs)?;
            }
        }

        tms_remain -= n;
    }

    ctx.prepare_for_read();

    let tail_len = num_bytes.min(tms_tail.len());
    if ctx.use_raw {
        xvc_log!(
            "Stream: {} bits, static RAW mode ({} bytes), TMS tail={:02x?}",
            num_bits,
            ctx.raw_len,
            &tms_tail[..tail_len]
        );
    } else {
        xvc_log!(
            "Stream: {} bits, {} RLE runs, TMS tail={:02x?}",
            num_bits,
            ctx.tms_rle.runs.len(),
            &tms_tail[..tail_len]
        );
    }

    let mut bits_remaining = num_bits;
    let mut total_processed = 0usize;
    let mut last_send_progress_ms = get_time_ms();

    while bits_remaining > 0 {
        let chunk_bits = core::cmp::min(bits_remaining, CHUNK_BITS);
        let chunk_bytes = bits_to_bytes(chunk_bits);

        while ctx.tdo_pending >= 2 {
            let ts = SmolInstant::from_millis(get_time_ms());
            iface.poll(ts, device, sockets);

            match try_drain_tdo(tcp_handle, ctx, iface, device, sockets) {
                DrainResult::Disconnected => return Err(StreamError::Disconnected),
                DrainResult::ProgressMade => last_send_progress_ms = get_time_ms(),
                DrainResult::NoProgress => {}
            }

            if ctx.tdo_pending >= 2 {
                if get_time_ms().saturating_sub(last_send_progress_ms) > STREAM_SEND_TIMEOUT_MS {
                    println!("Stream: TDO send stalled, client not reading");
                    return Err(StreamError::Timeout);
                }
                rtos_yield();
            }
        }

        match try_drain_tdo(tcp_handle, ctx, iface, device, sockets) {
            DrainResult::Disconnected => return Err(StreamError::Disconnected),
            DrainResult::ProgressMade => last_send_progress_ms = get_time_ms(),
            DrainResult::NoProgress => {}
        }

        ctx.fill_tms_into_buf(chunk_bytes)?;

        {
            let tdi_buf = unsafe { JTAG_BUFS.tdi_slice_mut() };
            read_exact_mix(
                tcp_handle,
                &mut tdi_buf[..chunk_bytes],
                xvc_rx,
                rx_head,
                rx_len,
                iface,
                device,
                sockets,
            )?;
        }

        let tdo_slot = ctx.current_tdo_slot();
        let tms_ptr = JTAG_BUFS.tms_ptr() as usize;
        let tdi_ptr = JTAG_BUFS.tdi_ptr() as usize;
        let tdo_ptr = JTAG_BUFS.tdo_ptr(tdo_slot) as usize;

        {
            let seq = next_seq();
            let _token = TokenGuard::acquire(seq).ok_or(StreamError::JtagFailed)?;

            MBOX.state.store(ST_IDLE, Ordering::Relaxed);
            MBOX.abort.store(false, Ordering::Relaxed);
            MBOX.tck_period_us
                .store(jtag.tck_period_us, Ordering::Relaxed);
            MBOX.num_bits.store(chunk_bits as u32, Ordering::Relaxed);
            MBOX.tms_ptr.store(tms_ptr, Ordering::Relaxed);
            MBOX.tdi_ptr.store(tdi_ptr, Ordering::Relaxed);
            MBOX.tdo_ptr.store(tdo_ptr, Ordering::Relaxed);
            MBOX.active_seq.store(seq, Ordering::Relaxed);

            if MBOX
                .cmd
                .compare_exchange(CMD_NONE, CMD_SHIFT, Ordering::Release, Ordering::Relaxed)
                .is_err()
            {
                println!("FATAL: cmd not consumed (stream)");
                unsafe { software_reset() };
            }

            let tck_us = jtag.tck_period_us as u64;
            let expected_ms = (chunk_bits as u64)
                .saturating_mul(tck_us)
                .saturating_add(999)
                / 1000;
            let deadline = Instant::now()
                + Duration::from_millis(expected_ms.saturating_mul(3).saturating_add(200));
            let hard_deadline = deadline + Duration::from_millis(2000);
            let mut soft_timeout = false;
            let mut disconnected = false;

            while MBOX.done_seq.load(Ordering::Acquire) != seq {
                let ts = SmolInstant::from_millis(get_time_ms());
                iface.poll(ts, device, sockets);

                if ctx.tdo_pending > 0 {
                    if let DrainResult::Disconnected =
                        try_drain_tdo(tcp_handle, ctx, iface, device, sockets)
                    {
                        if !disconnected {
                            disconnected = true;
                            MBOX.abort.store(true, Ordering::Release);
                        }
                    }
                }

                {
                    let socket = sockets.get_mut::<TcpSocket>(tcp_handle);
                    if !socket.may_recv() && !socket.may_send() && !disconnected {
                        disconnected = true;
                        MBOX.abort.store(true, Ordering::Release);
                    }
                }

                let now = Instant::now();
                if now > deadline && !soft_timeout {
                    let active_seq = JTAG_TOKEN.load(Ordering::Relaxed);
                    let state = MBOX.state.load(Ordering::Relaxed);
                    println!(
                        "Stream: chunk timeout (seq={}, state={}, pending={})",
                        active_seq, state, ctx.tdo_pending
                    );
                    MBOX.abort.store(true, Ordering::Release);
                    soft_timeout = true;
                }

                if now > hard_deadline {
                    println!("Stream: hard timeout, resetting");
                    unsafe { software_reset() };
                }

                rtos_yield();
            }

            if disconnected {
                return Err(StreamError::Disconnected);
            }

            if MBOX.state.load(Ordering::Acquire) != ST_DONE {
                return Err(StreamError::JtagFailed);
            }
        }

        unsafe {
            JTAG_BUFS.mask_tdo_last_byte(tdo_slot, chunk_bytes, chunk_bits);
        }

        ctx.enqueue_tdo(chunk_bytes);

        bits_remaining -= chunk_bits;
        total_processed += chunk_bits;

        if total_processed % 65_536 < CHUNK_BITS {
            xvc_log!("Stream: {}/{} bits", total_processed, num_bits);
        }
    }

    flush_tdo(tcp_handle, ctx, iface, device, sockets)?;

    let elapsed_ms = get_time_ms().saturating_sub(stream_start_ms);
    let bits_per_sec = if elapsed_ms > 0 {
        (num_bits as u64).saturating_mul(1000) / elapsed_ms as u64
    } else {
        0
    };

    xvc_log!(
        "Stream complete: {} bits in {}ms ({} kbit/s, TCK={}us)",
        num_bits,
        elapsed_ms,
        bits_per_sec / 1000,
        jtag.tck_period_us
    );

    Ok(())
}

