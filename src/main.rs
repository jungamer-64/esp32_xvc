// Parse "192.168.0.100" format at compile time with validation.
const fn parse_ip(s: &str) -> [u8; 4] {
    let b = s.as_bytes();
    let mut out = [0u8; 4];
    let mut oct = 0usize;
    let mut val: u16 = 0;
    let mut have_digit = false;

    let mut i = 0usize;
    while i < b.len() {
        let c = b[i];
        if c == b'.' {
            if !have_digit {
                panic!("bad ip: missing digit before dot");
            }
            if oct >= 3 {
                panic!("bad ip: too many octets");
            }
            if val > 255 {
                panic!("bad ip: octet > 255");
            }
            out[oct] = val as u8;
            oct += 1;
            val = 0;
            have_digit = false;
        } else if c >= b'0' && c <= b'9' {
            have_digit = true;
            val = val * 10 + (c - b'0') as u16;
            if val > 255 {
                panic!("bad ip: octet > 255");
            }
        } else {
            panic!("bad ip: invalid character");
        }
        i += 1;
    }
    if !have_digit {
        panic!("bad ip: missing final digit");
    }
    if oct != 3 {
        panic!("bad ip: not 4 octets");
    }
    out[oct] = val as u8;
    out
}

/// Convert a bit count to the minimum byte count without overflow.
const fn bits_to_bytes(bits: usize) -> usize {
    bits / 8 + if bits % 8 == 0 { 0 } else { 1 }
}

