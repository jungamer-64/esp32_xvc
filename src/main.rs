fn tap_reset_fast(tck_period_us: u32) -> bool {
    let high_us = ((tck_period_us + 1) / 2).max(1);
    let low_us = tck_period_us / 2;

    delay_us_coop(50);

    unsafe {
        fast_gpio::set_high(fast_gpio::TMS_MASK);
        fast_gpio::set_low(fast_gpio::TDI_MASK);
    }

    for i in 0..8 {
        if MBOX.abort.load(Ordering::Relaxed) {
            return false;
        }

        unsafe { fast_gpio::set_high(fast_gpio::TCK_MASK) };
        delay_us_coop(high_us);
        unsafe { fast_gpio::set_low(fast_gpio::TCK_MASK) };
        if low_us > 0 {
            delay_us_coop(low_us);
        }

        if tck_period_us > 100 && i % 2 == 1 {
            rtos_yield();
        }
    }

    unsafe { fast_gpio::set_low(fast_gpio::TMS_MASK) };
    unsafe { fast_gpio::set_high(fast_gpio::TCK_MASK) };
    delay_us_coop(high_us);
    unsafe { fast_gpio::set_low(fast_gpio::TCK_MASK) };
    if low_us > 0 {
        delay_us_coop(low_us);
    }

    true
}

fn shift_bits_fast(
    tck_period_us: u32,
    tms_bits: &[u8],
    tdi_bits: &[u8],
    tdo_out: &mut [u8],
    num_bits: usize,
) -> bool {
    let high_us = ((tck_period_us + 1) / 2).max(1);
    let low_us = tck_period_us / 2;

    let sample_us = (high_us / 2).max(1);
    let rest_high_us = high_us.saturating_sub(sample_us);

    let bit_us_approx = high_us + low_us + 4;
    let abort_check_bits = ((1000 / bit_us_approx).clamp(1, 4096)) as usize;
    let yield_bits = ((50_000 / bit_us_approx).clamp(1, 32_768)) as usize;

    let mut abort_counter = abort_check_bits;
    let mut yield_counter = yield_bits;
    let mut wdt_counter: u8 = 0;

    let num_bytes = bits_to_bytes(num_bits);
    for byte_idx in 0..num_bytes {
        let mut tms_byte = tms_bits[byte_idx];
        let mut tdi_byte = tdi_bits[byte_idx];
        let mut tdo_byte = 0u8;

        let bits_in_byte = if byte_idx == num_bytes - 1 {
            let rem = num_bits & 7;
            if rem == 0 { 8 } else { rem }
        } else {
            8
        };

        for bit_idx in 0..bits_in_byte {
            abort_counter -= 1;
            if abort_counter == 0 {
                abort_counter = abort_check_bits;
                if MBOX.abort.load(Ordering::Acquire) {
                    return false;
                }
            }

            yield_counter -= 1;
            if yield_counter == 0 {
                yield_counter = yield_bits;
                wdt_counter = wdt_counter.wrapping_add(1);
                if wdt_counter & 0x07 == 0 {
                    rtos_delay_ms(1);
                } else {
                    rtos_yield();
                }
            }

            let tms_bit = tms_byte & 1;
            let tdi_bit = tdi_byte & 1;

            unsafe {
                let set_mask = (if tms_bit == 1 { fast_gpio::TMS_MASK } else { 0 })
                    | (if tdi_bit == 1 { fast_gpio::TDI_MASK } else { 0 });
                let clear_mask = (if tms_bit == 0 { fast_gpio::TMS_MASK } else { 0 })
                    | (if tdi_bit == 0 { fast_gpio::TDI_MASK } else { 0 });
                fast_gpio::set_pins_with_fence(set_mask, clear_mask);
            }

            unsafe { fast_gpio::set_high(fast_gpio::TCK_MASK) };

            delay_us_coop(sample_us);

            if unsafe { fast_gpio::read_tdo() } {
                tdo_byte |= 1 << bit_idx;
            }

            if rest_high_us > 0 {
                delay_us_coop(rest_high_us);
            }

            unsafe { fast_gpio::set_low(fast_gpio::TCK_MASK) };
            if low_us > 0 {
                delay_us_coop(low_us);
            }

            tms_byte >>= 1;
            tdi_byte >>= 1;
        }

        tdo_out[byte_idx] = tdo_byte;
    }

    true
}

