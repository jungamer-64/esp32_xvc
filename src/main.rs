// =============================================================================
// TMS RLE COMPRESSION (for large 2-pass streaming shifts)
// =============================================================================

struct TmsRle {
    runs: alloc::vec::Vec<(u8, u32)>,
    run_idx: usize,
    run_left: u32,
}

impl TmsRle {
    fn new() -> Self {
        Self {
            runs: alloc::vec::Vec::new(),
            run_idx: 0,
            run_left: 0,
        }
    }

    fn clear(&mut self) {
        self.runs.clear();
        self.run_idx = 0;
        self.run_left = 0;
    }

    fn push_byte(&mut self, b: u8, max_runs: usize) -> Result<(), StreamError> {
        if let Some((last_b, last_len)) = self.runs.last_mut() {
            if *last_b == b && *last_len < u32::MAX {
                *last_len += 1;
                return Ok(());
            }
        }

        if self.runs.len() >= max_runs {
            return Err(StreamError::TmsRleOverflow);
        }

        if self.runs.try_reserve(1).is_err() {
            return Err(StreamError::OutOfMemory);
        }

        self.runs.push((b, 1));
        Ok(())
    }

    fn reset_cursor(&mut self) {
        self.run_idx = 0;
        self.run_left = 0;
    }

    fn fill(&mut self, out: &mut [u8]) -> Result<(), StreamError> {
        for o in out.iter_mut() {
            if self.run_left == 0 {
                if self.run_idx >= self.runs.len() {
                    return Err(StreamError::TmsUnderflow);
                }
                let (_, len) = self.runs[self.run_idx];
                self.run_left = len;
            }

            let (b, _) = self.runs[self.run_idx];
            *o = b;
            self.run_left -= 1;

            if self.run_left == 0 {
                self.run_idx += 1;
            }
        }
        Ok(())
    }
}

