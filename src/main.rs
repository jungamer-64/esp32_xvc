#[repr(align(8))]
#[allow(dead_code)]
struct AlignedHeapMem([u8; HEAP_SIZE]);

#[inline]
fn rtos_delay_ms(ms: u64) {
    CurrentThreadHandle::get().delay(Duration::from_millis(ms));
}

#[inline]
fn rtos_yield() {
    CurrentThreadHandle::get().delay(Duration::ZERO);
}

#[inline]
fn delay_us_coop(mut us: u32) {
    if us >= 2000 {
        while us > 0 {
            let chunk = us.min(250);
            ets_delay_us(chunk);
            us -= chunk;
            rtos_yield();
        }
    } else if us > 0 {
        ets_delay_us(us);
    }
}

fn init_heap() {
    use core::mem::MaybeUninit;

    static HEAP: StaticCell<MaybeUninit<AlignedHeapMem>> = StaticCell::new();
    let heap = HEAP.init_with(MaybeUninit::uninit);
    let heap_ptr = heap.as_mut_ptr() as *mut u8;

    unsafe {
        esp_alloc::HEAP.add_region(esp_alloc::HeapRegion::new(
            heap_ptr,
            HEAP_SIZE,
            esp_alloc::MemoryCapability::Internal.into(),
        ));
    }
}

/// Fast GPIO direct register access for ESP32 JTAG bit-banging.
mod fast_gpio {
    use core::ptr::{read_volatile, write_volatile};
    use core::sync::atomic::{Ordering, compiler_fence};

    const GPIO_OUT_W1TS: *mut u32 = 0x3FF44008 as *mut u32;
    const GPIO_OUT_W1TC: *mut u32 = 0x3FF4400C as *mut u32;
    const GPIO1_IN: *const u32 = 0x3FF44040 as *const u32;

    pub const TCK_MASK: u32 = 1 << 18;
    pub const TDI_MASK: u32 = 1 << 19;
    pub const TMS_MASK: u32 = 1 << 23;
    pub const TDO_BIT: u32 = 34 - 32;

    #[inline(always)]
    pub unsafe fn set_pins_with_fence(set_mask: u32, clear_mask: u32) {
        unsafe {
            if clear_mask != 0 {
                write_volatile(GPIO_OUT_W1TC, clear_mask);
            }
            if set_mask != 0 {
                write_volatile(GPIO_OUT_W1TS, set_mask);
            }
            core::arch::asm!("memw", options(nostack, preserves_flags));
        }
        compiler_fence(Ordering::Release);
    }

    #[inline(always)]
    pub unsafe fn set_high(mask: u32) {
        unsafe {
            write_volatile(GPIO_OUT_W1TS, mask);
            core::arch::asm!("memw", options(nostack, preserves_flags));
        }
    }

    #[inline(always)]
    pub unsafe fn set_low(mask: u32) {
        unsafe {
            write_volatile(GPIO_OUT_W1TC, mask);
            core::arch::asm!("memw", options(nostack, preserves_flags));
        }
    }

    #[inline(always)]
    pub unsafe fn read_tdo() -> bool {
        unsafe {
            core::arch::asm!("memw", options(nostack, preserves_flags));
            (read_volatile(GPIO1_IN) & (1 << TDO_BIT)) != 0
        }
    }
}

struct JtagController {
    _tck: Output<'static>,
    _tms: Output<'static>,
    _tdi: Output<'static>,
    _tdo: Input<'static>,
    tck_period_us: u32,
}

impl JtagController {
    fn set_tck_period(&mut self, period_ns: u32) {
        let period_us = period_ns
            .saturating_add(999)
            .checked_div(1000)
            .unwrap_or(0)
            .clamp(MIN_TCK_PERIOD_US, MAX_TCK_PERIOD_US);
        self.tck_period_us = period_us;
    }

    fn get_tck_period_ns(&self) -> u32 {
        self.tck_period_us.saturating_mul(1000)
    }
}

