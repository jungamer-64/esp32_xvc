//! ESP32 XVC Server - Bare Metal Implementation with Wi-Fi
//!
//! =============================================================================
//!  CRITICAL DESIGN REQUIREMENT — DO NOT REMOVE LARGE-SHIFT STREAMING
//! =============================================================================
//!
//! Vivado does NOT reliably respect the maximum shift size advertised by
//! `getinfo:`. It may unconditionally send shift commands far larger than the
//! normal in-memory XVC buffer can hold.
//!
//! Therefore, the streaming shift path is NOT an optional optimization,
//! experimental feature, or removable compatibility workaround. It is a
//! mandatory part of this server's Vivado compatibility.
//!
//! DO NOT:
//!
//! - remove `stream_shift_command`;
//! - replace all shift handling with one fixed-size receive buffer;
//! - reject every shift larger than `MAX_SHIFT_BITS`;
//! - assume the `getinfo:` advertised size limits what Vivado will send;
//! - simplify away the two-pass TMS/TDI streaming design.
//!
//! Removing or disabling large-shift streaming WILL make this server unable
//! to handle the oversized shift commands generated by Vivado and may cause
//! FPGA programming or JTAG operations to fail.
//!
//! The normal fixed-buffer path exists only for smaller shifts.
//! Any shift larger than `MAX_SHIFT_BITS` MUST be transferred to a bounded
//! streaming implementation or another functionally equivalent large-shift
//! path.
//!
//! If this implementation is refactored, the replacement MUST preserve:
//!
//! 1. support for shifts larger than the normal in-memory buffer;
//! 2. bounded RAM usage;
//! 3. storage or reconstruction of TMS until the corresponding TDI arrives;
//! 4. incremental JTAG execution and TDO transmission;
//! 5. timeout, disconnect, abort, and Core0/Core1 synchronization behavior.
//!
//! In short:
//!
//!     VIVADO MAY IGNORE GETINFO.
//!     FIXED-SIZE-ONLY SHIFT HANDLING IS NOT COMPATIBLE.
//!     LARGE-SHIFT STREAMING MUST NEVER BE REMOVED.
//!
//! =============================================================================
//!
//! XVC (Xilinx Virtual Cable) server for JTAG programming via Wi-Fi.
//! Uses esp-radio + esp-rtos for networking, smoltcp for TCP/IP.
//!
//! Refactored for stability:
//! - JTAG controller on stack (no unsafe static)
//! - Intermittent network polling during long shifts (no blocking)
//! - Robust error handling (closes connection on protocol violation)
//! - Lower TCK max period for TCP stability
//! - Overflow-safe XVC length and TCK parsing
//! - Deterministic static RAW TMS storage for the advertised GETINFO size
//! - Independent Wi-Fi link checks and reconnect retry timing

