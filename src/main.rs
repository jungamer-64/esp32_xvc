/// Mailbox for Core0 ↔ Core1 communication.
struct Mailbox {
    state: AtomicU32,
    cmd: AtomicU32,

    req_seq: AtomicU32,
    active_seq: AtomicU32,
    done_seq: AtomicU32,

    num_bits: AtomicU32,
    tck_period_us: AtomicU32,

    tms_ptr: AtomicUsize,
    tdi_ptr: AtomicUsize,
    tdo_ptr: AtomicUsize,

    abort: AtomicBool,
}

// SAFETY: All fields are atomic and may be shared between cores.
unsafe impl Sync for Mailbox {}

impl Mailbox {
    const fn new() -> Self {
        Self {
            state: AtomicU32::new(ST_IDLE),
            cmd: AtomicU32::new(CMD_NONE),
            req_seq: AtomicU32::new(0),
            active_seq: AtomicU32::new(0),
            done_seq: AtomicU32::new(0),
            num_bits: AtomicU32::new(0),
            tck_period_us: AtomicU32::new(MIN_TCK_PERIOD_US),
            tms_ptr: AtomicUsize::new(0),
            tdi_ptr: AtomicUsize::new(0),
            tdo_ptr: AtomicUsize::new(0),
            abort: AtomicBool::new(false),
        }
    }
}

static MBOX: Mailbox = Mailbox::new();

/// Value 0 means idle; a non-zero value is the active command sequence ID.
static JTAG_TOKEN: AtomicU32 = AtomicU32::new(0);

#[inline(always)]
fn next_seq() -> u32 {
    loop {
        let old = MBOX.req_seq.fetch_add(1, Ordering::Relaxed);
        let seq = old.wrapping_add(1);
        if seq != 0 {
            return seq;
        }
    }
}

struct TokenGuard {
    seq: u32,
}

impl TokenGuard {
    fn acquire(seq: u32) -> Option<Self> {
        debug_assert!(seq != 0, "Cannot acquire token with seq 0");
        JTAG_TOKEN
            .compare_exchange(0, seq, Ordering::AcqRel, Ordering::Acquire)
            .ok()
            .map(|_| TokenGuard { seq })
    }

    #[allow(dead_code)]
    fn seq(&self) -> u32 {
        self.seq
    }
}

impl Drop for TokenGuard {
    fn drop(&mut self) {
        JTAG_TOKEN.store(0, Ordering::Release);
    }
}

